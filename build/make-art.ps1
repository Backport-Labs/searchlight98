# Draws Searchlight 98's artwork with System.Drawing:
#   app\SLIGHT98.ICO       program icon (32x32 and 16x16, transparent)
#   src\icon.h             the same icon as C data, compiled into SLIGHT98.EXE
#   installer\WIZARD.BMP   164x314 side image for the setup wizard
#   installer\WIZSMALL.BMP 55x55 corner image for the setup wizard
param([string]$Root = (Split-Path -Parent $PSScriptRoot))
Add-Type -AssemblyName System.Drawing
$ErrorActionPreference = 'Stop'

function New-Logo([int]$size) {
    # Magnifying glass with a yellow searchlight beam, on a transparent background.
    $bmp = New-Object System.Drawing.Bitmap $size, $size, ([System.Drawing.Imaging.PixelFormat]::Format32bppArgb)
    $g = [System.Drawing.Graphics]::FromImage($bmp)
    $g.SmoothingMode = 'AntiAlias'
    $g.Clear([System.Drawing.Color]::Transparent)
    $s = $size / 32.0
    $beam = New-Object System.Drawing.Drawing2D.GraphicsPath
    $beam.AddPolygon([System.Drawing.PointF[]]@(
        (New-Object System.Drawing.PointF (13*$s), (13*$s)),
        (New-Object System.Drawing.PointF (31*$s), (1*$s)),
        (New-Object System.Drawing.PointF (31*$s), (13*$s))))
    $g.FillPath((New-Object System.Drawing.SolidBrush ([System.Drawing.Color]::FromArgb(255, 255, 230, 60))), $beam)
    $lens = New-Object System.Drawing.RectangleF (3*$s), (3*$s), (18*$s), (18*$s)
    $g.FillEllipse((New-Object System.Drawing.SolidBrush ([System.Drawing.Color]::FromArgb(255, 170, 215, 255))), $lens)
    $g.DrawEllipse((New-Object System.Drawing.Pen ([System.Drawing.Color]::FromArgb(255, 0, 0, 128)), ([single](3*$s))), $lens)
    $handle = New-Object System.Drawing.Pen ([System.Drawing.Color]::FromArgb(255, 0, 0, 128)), ([single](5*$s))
    $handle.StartCap = 'Round'; $handle.EndCap = 'Round'
    $g.DrawLine($handle, (19*$s), (19*$s), (28*$s), (28*$s))
    $g.FillEllipse((New-Object System.Drawing.SolidBrush ([System.Drawing.Color]::FromArgb(200, 255, 255, 255))), (7*$s), (7*$s), (5*$s), (5*$s))
    $g.Dispose()
    return $bmp
}

function Get-IcoImage([System.Drawing.Bitmap]$bmp) {
    # 24-bit colour plus 1-bit transparency mask, as Windows 95/98 expect.
    $n = $bmp.Width
    $stride = [int](($n * 3 + 3) -band -4)
    $andStride = [int]([math]::Floor(($n + 31) / 32) * 4)
    $xor = New-Object byte[] ($stride * $n)
    $and = New-Object byte[] ($andStride * $n)
    for ($y = 0; $y -lt $n; $y++) {
        $row = $n - 1 - $y                           # bottom-up
        for ($x = 0; $x -lt $n; $x++) {
            $c = $bmp.GetPixel($x, $y)
            $o = $row * $stride + $x * 3
            if ($c.A -lt 128) {
                $and[$row * $andStride + [math]::Floor($x / 8)] = $and[$row * $andStride + [math]::Floor($x / 8)] -bor (0x80 -shr ($x % 8))
            } else {
                $xor[$o] = $c.B; $xor[$o + 1] = $c.G; $xor[$o + 2] = $c.R
            }
        }
    }
    $ms = New-Object System.IO.MemoryStream
    $w = New-Object System.IO.BinaryWriter $ms
    $w.Write([int]40); $w.Write([int]$n); $w.Write([int]($n * 2)); $w.Write([int16]1); $w.Write([int16]24)
    $w.Write([int]0); $w.Write([int]0); $w.Write([int]0); $w.Write([int]0); $w.Write([int]0); $w.Write([int]0)
    $w.Write($xor); $w.Write($and); $w.Flush()
    return ,$ms.ToArray()
}

function Save-Ico([string]$path, [int[]]$sizes) {
    $images = @(); foreach ($s in $sizes) { $images += ,(Get-IcoImage (New-Logo $s)) }
    $fs = [System.IO.File]::Create($path); $w = New-Object System.IO.BinaryWriter $fs
    $w.Write([int16]0); $w.Write([int16]1); $w.Write([int16]$sizes.Count)
    $offset = 6 + 16 * $sizes.Count
    for ($i = 0; $i -lt $sizes.Count; $i++) {
        $w.Write([byte]$sizes[$i]); $w.Write([byte]$sizes[$i]); $w.Write([byte]0); $w.Write([byte]0)
        $w.Write([int16]1); $w.Write([int16]24); $w.Write([int]$images[$i].Length); $w.Write([int]$offset)
        $offset += $images[$i].Length
    }
    foreach ($img in $images) { $w.Write($img) }
    $w.Close()
}

function Save-Bmp24([System.Drawing.Bitmap]$bmp, [string]$path) {
    $out = New-Object System.Drawing.Bitmap $bmp.Width, $bmp.Height, ([System.Drawing.Imaging.PixelFormat]::Format24bppRgb)
    $g = [System.Drawing.Graphics]::FromImage($out); $g.DrawImage($bmp, 0, 0, $bmp.Width, $bmp.Height); $g.Dispose()
    $out.Save($path, [System.Drawing.Imaging.ImageFormat]::Bmp); $out.Dispose()
}

$app = Join-Path $Root 'app'; $ins = Join-Path $Root 'installer'
New-Item -ItemType Directory -Force $app, $ins | Out-Null
$navy = [System.Drawing.Color]::FromArgb(0, 0, 128); $blue = [System.Drawing.Color]::FromArgb(16, 132, 208)

Save-Ico (Join-Path $app 'SLIGHT98.ICO') @(32, 16)

# The icon as C data. Each array is one icon image: header, colours, mask.
$ico = [System.IO.File]::ReadAllBytes((Join-Path $app 'SLIGHT98.ICO'))
$sb = New-Object System.Text.StringBuilder
[void]$sb.Append("/* Searchlight 98 icon artwork. Generated by build\make-art.ps1 from app\SLIGHT98.ICO. */`r`n")
for ($i = 0; $i -lt [BitConverter]::ToUInt16($ico, 4); $i++) {
    $e = 6 + 16 * $i
    $size = [BitConverter]::ToInt32($ico, $e + 8); $off = [BitConverter]::ToInt32($ico, $e + 12)
    [void]$sb.Append("static const unsigned char ICON$($ico[$e])[$size] = {`r`n")
    for ($k = 0; $k -lt $size; $k += 20) {
        $last = [math]::Min($off + $k + 19, $off + $size - 1)
        $line = ($ico[($off + $k)..$last] | ForEach-Object { '0x{0:X2}' -f $_ }) -join ','
        [void]$sb.Append('    ' + $line + $(if ($k + 20 -lt $size) { ',' } else { '' }) + "`r`n")
    }
    [void]$sb.Append("};`r`n")
}
[System.IO.File]::WriteAllText((Join-Path $Root 'src\icon.h'), $sb.ToString(), [System.Text.Encoding]::ASCII)

# Wizard side image
$wz = New-Object System.Drawing.Bitmap 164, 314
$g = [System.Drawing.Graphics]::FromImage($wz); $g.SmoothingMode = 'AntiAlias'; $g.TextRenderingHint = 'AntiAlias'
$g.FillRectangle((New-Object System.Drawing.Drawing2D.LinearGradientBrush (New-Object System.Drawing.Rectangle 0, 0, 164, 314), $navy, $blue, 90.0), 0, 0, 164, 314)
$cone = New-Object System.Drawing.Drawing2D.GraphicsPath
$cone.AddPolygon([System.Drawing.PointF[]]@((New-Object System.Drawing.PointF 20, 300), (New-Object System.Drawing.PointF 60, 0), (New-Object System.Drawing.PointF 164, 0), (New-Object System.Drawing.PointF 164, 60)))
$g.FillPath((New-Object System.Drawing.SolidBrush ([System.Drawing.Color]::FromArgb(60, 255, 240, 150))), $cone)
$logo = New-Logo 96; $g.DrawImage($logo, 34, 60, 96, 96)
$fontBig = New-Object System.Drawing.Font 'Tahoma', 17, ([System.Drawing.FontStyle]::Bold)
$fontNum = New-Object System.Drawing.Font 'Tahoma', 30, ([System.Drawing.FontStyle]::Bold)
$fmt = New-Object System.Drawing.StringFormat; $fmt.Alignment = 'Center'
$g.DrawString('Searchlight', $fontBig, [System.Drawing.Brushes]::White, (New-Object System.Drawing.RectangleF 0, 190, 164, 30), $fmt)
$g.DrawString('98', $fontNum, (New-Object System.Drawing.SolidBrush ([System.Drawing.Color]::FromArgb(255, 230, 60))), (New-Object System.Drawing.RectangleF 0, 220, 164, 50), $fmt)
$g.Dispose(); Save-Bmp24 $wz (Join-Path $ins 'WIZARD.BMP')

# Wizard corner image
$sm = New-Object System.Drawing.Bitmap 55, 55
$g = [System.Drawing.Graphics]::FromImage($sm); $g.SmoothingMode = 'AntiAlias'
$g.Clear([System.Drawing.Color]::White); $g.DrawImage((New-Logo 48), 4, 4, 48, 48); $g.Dispose()
Save-Bmp24 $sm (Join-Path $ins 'WIZSMALL.BMP')

Get-ChildItem $app, $ins -File | Where-Object { $_.Extension -in '.ICO', '.BMP' } | Select-Object Name, Length
